"""
main.py — FastAPI application entry point.

Endpoints
---------
GET  /api/health      → {"status": "ok"}
POST /api/summarize   → SummaryResponse JSON
GET  /                → Serves frontend/index.html (and all static assets)
GET  /docs            → Swagger UI (auto-generated by FastAPI)

Requires GROQ_API_KEY to be set — the server will refuse to start without it.
"""

from __future__ import annotations

import logging
import time
from pathlib import Path

from fastapi import FastAPI, File, HTTPException, UploadFile
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import JSONResponse
from fastapi.staticfiles import StaticFiles

from backend.config import settings
from backend.llm_client import summarise
from backend.parser import parse_pdf
from backend.schemas import SummaryResponse

# ── Logging ───────────────────────────────────────────────────────────────────
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s  %(levelname)-8s  %(name)s — %(message)s",
)
logger = logging.getLogger(__name__)

# ── App ───────────────────────────────────────────────────────────────────────
app = FastAPI(
    title="AI-Powered Text Summarizer for Research Papers",
    description=(
        "Upload a research paper PDF and receive a structured four-section "
        "summary powered by the Groq LLM API. "
        "Requires GROQ_API_KEY to be configured."
    ),
    version="1.0.0",
    docs_url="/docs",
    redoc_url="/redoc",
)


@app.on_event("startup")
async def startup_check() -> None:
    """Validate required configuration on server startup."""
    settings.validate_api_key()
    logger.info("Groq API key validated. Server is ready.")

# Allow the Vite/browser dev-server origin during development.
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

# ── Routes ────────────────────────────────────────────────────────────────────


@app.get("/api/health", tags=["health"], summary="Health check")
async def health() -> dict[str, str]:
    """Returns a simple liveness indicator."""
    return {"status": "ok"}


@app.post(
    "/api/summarize",
    response_model=SummaryResponse,
    tags=["summarization"],
    summary="Summarise a research paper PDF",
)
async def summarize_paper(file: UploadFile = File(...)) -> SummaryResponse:
    """
    Accept a PDF research paper, extract and clean its text, then return a
    structured four-section summary.

    - **file**: A `.pdf` file ≤ 10 MB.
    """
    # ── Validate file type ────────────────────────────────────────────────────
    filename = file.filename or "upload.pdf"
    if not filename.lower().endswith(".pdf"):
        raise HTTPException(
            status_code=400,
            detail="Only PDF files are accepted. Please upload a .pdf file.",
        )

    # ── Read and validate file size ───────────────────────────────────────────
    raw_bytes = await file.read()
    if len(raw_bytes) > settings.max_file_size_bytes:
        limit_mb = settings.max_file_size_bytes / (1024 * 1024)
        raise HTTPException(
            status_code=413,
            detail=f"File is too large. Maximum allowed size is {limit_mb:.0f} MB.",
        )

    if len(raw_bytes) == 0:
        raise HTTPException(status_code=400, detail="Uploaded file is empty.")

    logger.info("Received file: %s (%d bytes)", filename, len(raw_bytes))
    start_time = time.perf_counter()

    # ── Parse PDF ─────────────────────────────────────────────────────────────
    try:
        doc = parse_pdf(raw_bytes)
    except ValueError as exc:
        raise HTTPException(status_code=422, detail=str(exc)) from exc
    except Exception as exc:
        logger.exception("Unexpected error during PDF parsing.")
        raise HTTPException(
            status_code=500, detail="Internal error while parsing the PDF."
        ) from exc

    logger.info("Extracted %d pages, %d characters.", doc.pages, len(doc.text))

    # ── LLM Summarisation ─────────────────────────────────────────────────────
    try:
        summary_sections = await summarise(doc.text)
    except RuntimeError as exc:
        logger.error("LLM summarisation failed: %s", exc)
        raise HTTPException(status_code=502, detail=str(exc)) from exc
    except Exception as exc:
        logger.exception("Unexpected error during summarisation.")
        raise HTTPException(
            status_code=500, detail="Internal error during summarisation."
        ) from exc

    elapsed = round(time.perf_counter() - start_time, 3)
    logger.info("Request completed in %.3f s.", elapsed)

    return SummaryResponse(
        filename=filename,
        pages=doc.pages,
        summary=summary_sections,
        processing_time_s=elapsed,
    )


# ── Static files (frontend) ───────────────────────────────────────────────────
# Mounted AFTER API routes so /api/* is never shadowed.
_FRONTEND_DIR = Path(__file__).parent.parent / "frontend"

if _FRONTEND_DIR.exists():
    app.mount("/", StaticFiles(directory=str(_FRONTEND_DIR), html=True), name="frontend")
    logger.info("Serving frontend from %s", _FRONTEND_DIR)
else:
    logger.warning("Frontend directory not found at %s — UI will not be served.", _FRONTEND_DIR)
